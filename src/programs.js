export function findProgram(id) {
  return programs.find((program) => program.id === id) ?? null
}

// 給執行器帶進 Agent 提示詞的參考資料。只輸出事實，不含判斷。
export function buildProgramBrief(ids) {
  const picked = (ids ?? []).map(findProgram).filter(Boolean)
  if (!picked.length) return ''

  return picked
    .map((program) => {
      const lines = [
        `【${program.code}　${program.name}】`,
        `主管機關：${program.authority}`,
        `適用對象：${program.target}`,
        '',
        '階段與金額：',
        ...program.stages.map(
          (stage) => `- ${stage.code} ${stage.name}：${stage.money.join('；')}。${stage.note}`
        ),
        '',
        '申請資格：',
        ...program.eligibility.map((item) => `- ${item}`),
        '',
        '不得申請的情形：',
        ...program.excluded.map((item) => `- ${item}`),
      ]

      if (program.evidence.length) {
        lines.push('', '受影響佐證類型：')
        program.evidence.forEach((row) => lines.push(`- ${row.type}：${row.proof}`))
      }
      if (program.ratioChecks.length) {
        lines.push('', '經費比例上限：')
        program.ratioChecks.forEach((row) =>
          lines.push(`- ${row.item} 不得超過${row.base}之 ${row.limit}%`)
        )
      }
      if (program.deadlines.length) {
        lines.push('', '期限規定：')
        program.deadlines.forEach((row) => lines.push(`- ${row.item}：${row.rule}`))
      }
      if (program.accounting.length) {
        lines.push('', '會計與核銷規定：')
        program.accounting.forEach((item) => lines.push(`- ${item}`))
      }
      if (program.cautions.length) {
        lines.push('', '注意事項：')
        program.cautions.forEach((item) => lines.push(`- ${item}`))
      }
      lines.push('', `罰則：${program.penalty}`)
      return lines.join('\n')
    })
    .join('\n\n')
    .concat('\n\n【資料性質】\n' + programNote)
}
